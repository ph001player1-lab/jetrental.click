/** Переводчик для языка: { t(key, params), dateTime(ms), lang } */
export function dashboardTranslator(lang) {
  const code = DASHBOARD_LANGS.includes(lang) ? lang : 'en';
  const format = new Intl.DateTimeFormat(LOCALES[code], {
    timeZone: 'Asia/Bangkok', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', hourCycle: 'h23'
  });
  const t = (key, params = {}) => String(TEXTS[code][key] ?? TEXTS.en[key] ?? key)
    .replace(/\{(\w+)\}/g, (m, name) => (name in params ? params[name] : m));
  return { lang: code, t, dateTime: (ms) => format.format(new Date(ms)) };
}
